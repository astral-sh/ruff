"""Generate the lexer's keyword table and collision-free hash multiplier.

Edit KEYWORDS below, then run `uv run scripts/generate_keyword_hash.py`.
The generated Rust data is written to `crates/ruff_python_parser/src/lexer/keywords.rs`.
"""

from __future__ import annotations

import random
from pathlib import Path

OUTPUT_PATH = (
    Path(__file__).resolve().parents[1]
    / "crates/ruff_python_parser/src/lexer/keywords.rs"
)
U64_MASK = (1 << 64) - 1

# Both hard and soft keywords receive distinct token kinds in the lexer.
KEYWORDS = [
    ("False", "False"),
    ("None", "None"),
    ("True", "True"),
    ("and", "And"),
    ("as", "As"),
    ("assert", "Assert"),
    ("async", "Async"),
    ("await", "Await"),
    ("break", "Break"),
    ("case", "Case"),
    ("class", "Class"),
    ("continue", "Continue"),
    ("def", "Def"),
    ("del", "Del"),
    ("elif", "Elif"),
    ("else", "Else"),
    ("except", "Except"),
    ("finally", "Finally"),
    ("for", "For"),
    ("from", "From"),
    ("global", "Global"),
    ("if", "If"),
    ("import", "Import"),
    ("in", "In"),
    ("is", "Is"),
    ("lazy", "Lazy"),
    ("lambda", "Lambda"),
    ("match", "Match"),
    ("nonlocal", "Nonlocal"),
    ("not", "Not"),
    ("or", "Or"),
    ("pass", "Pass"),
    ("raise", "Raise"),
    ("return", "Return"),
    ("try", "Try"),
    ("type", "Type"),
    ("while", "While"),
    ("with", "With"),
    ("yield", "Yield"),
]


def find_multiplier(words: list[int]) -> int:
    """Find a multiplier whose high six product bits uniquely identify each word."""
    random_source = random.Random(0)
    for _ in range(10_000_000):
        multiplier = random_source.getrandbits(64) | 1
        slots = set()
        for word in words:
            # Match Rust's wrapping_mul followed by a shift of 58 bits.
            slot = ((word * multiplier) & U64_MASK) >> 58
            if slot in slots:
                break
            slots.add(slot)
        else:
            return multiplier

    raise SystemExit("No multiplier found; the keyword hash may need a larger table.")


def main() -> None:
    keywords = [keyword for keyword, _ in KEYWORDS]
    if len(set(keywords)) != len(keywords):
        raise SystemExit("The keyword list contains duplicate spellings.")
    if any(
        not (keyword.isascii() and keyword.isidentifier() and 2 <= len(keyword) <= 8)
        for keyword in keywords
    ):
        raise SystemExit("Keywords must be ASCII identifiers of two to eight bytes.")

    # Match KeywordTable::new: little-endian bytes aligned to the high end of a u64.
    words = [
        int.from_bytes(keyword.encode("ascii"), "little") << ((8 - len(keyword)) * 8)
        for keyword in keywords
    ]
    multiplier = find_multiplier(words)
    entries = "".join(
        f'    (b"{keyword}", TokenKind::{kind}),\n' for keyword, kind in KEYWORDS
    )
    OUTPUT_PATH.write_text(
        "//! This file is generated by `scripts/generate_keyword_hash.py`.\n"
        "\n"
        "use ruff_python_ast::token::TokenKind;\n"
        "\n"
        "use super::KeywordTable;\n"
        "\n"
        f"pub(super) const KEYWORD_HASH_MULTIPLIER: u64 = 0x{multiplier:_x};\n"
        "\n"
        "pub(super) static KEYWORD_TABLE: KeywordTable = KeywordTable::new(&[\n"
        f"{entries}"
        "]);\n"
    )


if __name__ == "__main__":
    main()
