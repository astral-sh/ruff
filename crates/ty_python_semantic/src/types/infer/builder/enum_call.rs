/// Result of parsing the `names` argument of a functional enum call.
enum EnumMembersArgParseResult<'ast> {
    /// Member names whose values are generated by the functional API.
    Names(Vec<Name>),
    /// Explicit namespace entries, including any ordinary class attributes.
    Pairs(Vec<(Name, &'ast ast::Expr)>),
    /// The argument is valid, but some members are not known precisely.
    Unknown,
    /// The argument is definitely invalid for functional enum creation.
    Invalid,
}

/// Distinguishes whether member values are auto-generated from names or provided explicitly.
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
enum EnumMemberValueForm {
    /// Values are derived from member names via the enum's implicit auto-value rules.
    Generated,
    /// Values are supplied directly by the functional enum input.
    Explicit,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum EnumEntryKind {
    Member,
    Nonmember,
}

/// A union can be exposed precisely when all alternatives agree on membership.
fn classify_enum_value<'db>(
    db: &'db dyn Db,
    env: &ProgramEnvironment<'db>,
    value: Type<'db>,
    next_value: impl Fn() -> Type<'db>,
) -> Option<(EnumEntryKind, Type<'db>)> {
    let resolve_auto = |ty| {
        if enum_marker_class(db, env, ty) == Some(KnownClass::Auto) {
            next_value()
        } else {
            ty
        }
    };
    let classify = |ty| {
        let marker = enum_marker_class(db, env, ty);
        if marker == Some(KnownClass::Nonmember) {
            (EnumEntryKind::Nonmember, enum_wrapper_value(db, env, ty))
        } else if is_enum_descriptor(db, env, ty) {
            (EnumEntryKind::Nonmember, ty)
        } else {
            let value = match marker {
                Some(KnownClass::Auto) => next_value(),
                Some(KnownClass::Member) => {
                    let inner = enum_wrapper_value(db, env, ty);
                    match inner.as_union_like(db) {
                        Some(union) => union.map(db, env, |&ty| resolve_auto(ty)),
                        None => resolve_auto(inner),
                    }
                }
                _ => ty,
            };
            (EnumEntryKind::Member, value)
        }
    };
    let Some(union) = value.as_union_like(db) else {
        return Some(classify(value));
    };
    let mut common_kind = None;
    let value = union.try_map(db, env, |&ty| {
        let (kind, value) = classify(ty);
        (*common_kind.get_or_insert(kind) == kind).then_some(value)
    })?;
    Some((common_kind?, value))
}

#[derive(Copy, Clone, Debug, Eq, PartialEq)]
enum TypeMixinMemberBehavior {
    /// Preserve both member names and values precisely.
    Precise,
    /// Convert generated values through a known builtin mixin, widening when exact literals are
    /// not representable or would be impractical to materialize.
    ConvertedValues,
    /// Hide the member set entirely because the mixin may change canonical members or aliasing.
    UnknownMembers,
}

impl TypeMixinMemberBehavior {
    /// Classifies how much member information can be preserved for a functional enum with `type=`.
    ///
    /// Generated-name forms can keep more information for a small set of builtin mixins whose value
    /// conversion rules we model explicitly. Explicit-value forms are treated more conservatively,
    /// since applying the mixin can change aliasing and therefore the canonical member set.
    fn from_mixin(db: &dyn Db, mixin_type: Type<'_>, value_form: EnumMemberValueForm) -> Self {
        match value_form {
            EnumMemberValueForm::Explicit => Self::UnknownMembers,
            EnumMemberValueForm::Generated => match mixin_type {
                Type::ClassLiteral(ClassLiteral::Static(class)) => match class.known(db) {
                    Some(KnownClass::Int) => Self::Precise,
                    Some(KnownClass::Str | KnownClass::Bytes | KnownClass::Float) => {
                        Self::ConvertedValues
                    }
                    _ => Self::UnknownMembers,
                },
                _ => Self::UnknownMembers,
            },
        }
    }
}

/// Classification of one element in a sequence-form `names` argument.
enum SequenceEnumMember<'ast> {
    /// A known string member name like `"RED"`.
    NameKnown(Name),
    /// A name entry whose type is compatible with `str`, but not precise.
    NameOpaque,
    /// A known `(name, value)` pair like `("RED", 1)`.
    PairKnown(Name, &'ast ast::Expr),
    /// A potential `(name, value)` pair whose name position is not precise.
    PairOpaque,
    /// An element that cannot participate in functional enum member parsing.
    Invalid,
}

/// Distinguishes whether a sequence-form `names` argument uses bare names or explicit pairs.
#[derive(Copy, Clone)]
enum SequenceEnumMemberForm {
    /// The sequence is a list of member names.
    Names,
    /// The sequence is a list of explicit `(name, value)` pairs.
    Pairs,
}

/// Find enum base class of the given type.
pub(crate) fn enum_functional_call_base<'db>(db: &'db dyn Db, ty: Type<'db>) -> Option<KnownClass> {
    ty.as_class_literal()?
        .known(db)
        .filter(|known| known.is_builtin_enum_base())
}

fn enum_functional_call_keyword_is_valid(name: &str, python_version: PythonVersion) -> bool {
    matches!(
        name,
        "value" | "names" | "start" | "type" | "module" | "qualname"
    ) || (name == "boundary" && python_version >= PythonVersion::PY311)
}

/// Returns the effective `_EnumNames` type accepted by the functional enum APIs.
///
/// This includes the string form, iterables of strings, iterables of
/// iterable-like `(name, value)` pairs, and mappings from `str` to values.
fn enum_names_type<'db>(db: &'db dyn Db, env: &ProgramEnvironment<'db>) -> Type<'db> {
    let str_type = KnownClass::Str.to_instance(db, env);
    let iterable_str = KnownClass::Iterable.to_specialized_instance(db, env, &[str_type]);
    let iterable_object = KnownClass::Iterable.to_specialized_instance(db, env, &[Type::object()]);
    let iterable_iterable_object =
        KnownClass::Iterable.to_specialized_instance(db, env, &[iterable_object]);
    let mapping_str_object = KnownClass::Mapping.to_specialized_instance(
        db,
        env,
        &[KnownClass::Str.to_instance(db, env), Type::object()],
    );
    UnionType::from_elements(
        db,
        env,
        [
            str_type,
            iterable_str,
            iterable_iterable_object,
            mapping_str_object,
        ],
    )
}

fn enum_names_from_string(s: &str) -> impl Iterator<Item = Name> + '_ {
    s.split(|c: char| c == ',' || c.is_whitespace())
        .filter(|name| !name.is_empty())
        .map(Name::new)
}

/// The functional API takes verbatim names, so `__private` is only special if it
/// is already mangled for this enum.
fn is_enum_attribute_name(name: &str, class_name: Option<&str>, version: PythonVersion) -> bool {
    let dunder = name
        .strip_prefix("__")
        .and_then(|rest| rest.strip_suffix("__"))
        .is_some_and(|inner| !inner.is_empty() && !inner.starts_with('_') && !inner.ends_with('_'));
    let sunder = name.len() > 2 && ast::helpers::is_sunder(name);
    let private = version >= PythonVersion::PY311
        && !name.ends_with("__")
        && class_name.is_some_and(|class| {
            name.strip_prefix('_')
                .and_then(|rest| rest.strip_prefix(class))
                .and_then(|rest| rest.strip_prefix("__"))
                .is_some_and(|suffix| !suffix.is_empty())
        });
    dunder || sunder || private
}

fn enum_members_from_names<'db>(
    context: &InferContext<'db, '_>,
    names: Vec<Name>,
    start: Type<'db>,
    base_class: KnownClass,
) -> Vec<(Name, Type<'db>)> {
    let db = context.db();
    let env = context.program_environment();
    let mut members = Vec::with_capacity(names.len());
    let mut history = EnumAutoHistory::default();

    for (index, name) in names.into_iter().enumerate() {
        // StrEnum generates every value from the member name, including the first.
        let value = if index == 0 && base_class != KnownClass::StrEnum {
            start
        } else {
            history.next_value(db, env, base_class, name.as_str())
        };
        history = history.with_value(db, env, value);
        members.push((name, value));
    }

    members
}

/// Converts generated functional-enum member values through a known builtin `type=` mixin.
///
/// This preserves exact `str` literals when the generated auto-values are known integer literals,
/// otherwise preserving at least the builtin result type for `str`, `bytes`, and `float`.
///
/// Returns `None` when the mixin is not a supported builtin or when the generated values are not
/// compatible with the corresponding builtin conversion.
fn apply_generated_type_mixin_member_values<'db>(
    context: &InferContext<'db, '_>,
    mixin_type: Type<'_>,
    members: Vec<(Name, Type<'db>)>,
) -> Option<Vec<(Name, Type<'db>)>> {
    let db = context.db();
    let Type::ClassLiteral(ClassLiteral::Static(class)) = mixin_type else {
        return None;
    };

    let mixin_class @ (KnownClass::Str | KnownClass::Bytes | KnownClass::Float) =
        class.known(db)?
    else {
        return None;
    };

    let env = context.program_environment();
    members
        .into_iter()
        .map(|(name, value)| {
            if !value.is_assignable_to(db, env, KnownClass::Int.to_instance(db, env)) {
                return None;
            }

            let value = if mixin_class == KnownClass::Str
                && let Some(literal) = value.as_int_literal()
            {
                Type::string_literal(db, literal.to_compact_string())
            } else {
                mixin_class.to_instance(db, env)
            };
            Some((name, value))
        })
        .collect()
}

impl<'db> TypeInferenceBuilder<'db, '_> {
    pub(crate) fn infer_enum_call_expression(
        &mut self,
        call_expr: &ast::ExprCall,
        definition: Option<Definition<'db>>,
        base_class: KnownClass,
    ) -> Option<Type<'db>> {
        let db = self.db();
        let ast::Arguments {
            args,
            keywords,
            range: _,
            node_index: _,
        } = &call_expr.arguments;

        for kw in keywords {
            let Some(name) = &kw.arg else {
                continue;
            };
            let env = self.program_environment();
            let python_version = env.python_version(db);
            if !enum_functional_call_keyword_is_valid(name.as_str(), python_version)
                && let Some(builder) = self.context.report_lint(&UNKNOWN_ARGUMENT, kw)
            {
                builder.into_diagnostic(format_args!(
                    "Argument `{name}` does not match any known parameter of function `{base_name}`",
                    base_name = base_class.name(env.python_version(db)),
                ));
            }
        }

        let value_kw = call_expr.arguments.find_keyword("value");
        let names_kw = call_expr.arguments.find_keyword("names");
        let start_kw = call_expr.arguments.find_keyword("start");
        let type_kw = call_expr.arguments.find_keyword("type");

        let has_positional_keyword_conflict =
            (!args.is_empty() && value_kw.is_some()) || (args.len() >= 2 && names_kw.is_some());
        if !args.is_empty()
            && let Some(keyword) = value_kw
            && let Some(builder) = self
                .context
                .report_lint(&PARAMETER_ALREADY_ASSIGNED, keyword)
        {
            builder.into_diagnostic(format_args!(
                "Multiple values provided for parameter `value` of `{base_name}()`",
                base_name = base_class.name(self.program_environment().python_version(db)),
            ));
        }
        if args.len() >= 2
            && let Some(keyword) = names_kw
            && let Some(builder) = self
                .context
                .report_lint(&PARAMETER_ALREADY_ASSIGNED, keyword)
        {
            builder.into_diagnostic(format_args!(
                "Multiple values provided for parameter `names` of `{base_name}()`",
                base_name = base_class.name(self.program_environment().python_version(db)),
            ));
        }

        let (name_arg, names_arg): (Option<&ast::Expr>, Option<&ast::Expr>) = match &**args {
            [name, names, ..] => (Some(name), Some(names)),
            [name] => (Some(name), names_kw.map(|kw| &kw.value)),
            [] => (value_kw.map(|kw| &kw.value), names_kw.map(|kw| &kw.value)),
        };

        let name_arg = name_arg?;
        let env = self.program_environment();

        for arg in args {
            self.infer_expression(arg, TypeContext::default());
        }
        for kw in keywords {
            self.infer_expression(&kw.value, TypeContext::default());
        }

        let name_type = self.expression_type(name_arg);
        let name = self.infer_enum_name_argument(name_arg, name_type, base_class);

        let Some(names_arg) = names_arg else {
            if let Some(keyword) = start_kw {
                self.infer_enum_start_argument(&keyword.value);
            }
            if let Some(keyword) = type_kw {
                self.infer_enum_mixin_argument(&keyword.value, base_class);
            }

            let python_version = self.program_environment().python_version(db);
            if let Some(builder) = self.context.report_lint(&MISSING_ARGUMENT, call_expr) {
                builder.into_diagnostic(format_args!(
                    "Missing required argument `names` to `{base_name}()`",
                    base_name = base_class.name(python_version),
                ));
            }

            return Some(base_class.to_instance(db, env));
        };

        let start = start_kw.map_or(Type::int_literal(1), |kw| {
            self.infer_enum_start_argument(&kw.value)
        });
        let (mixin_type, valid_mixin_type) = type_kw.map_or((None, true), |kw| {
            self.infer_enum_mixin_argument(&kw.value, base_class)
        });

        // Only 1 extra positional arg is allowed (the `names` parameter).
        // `Enum("Color", "RED", "GREEN")` is invalid at runtime.
        let has_too_many_positional = args.len() > 2;
        if has_too_many_positional
            && let Some(builder) = self
                .context
                .report_lint(&TOO_MANY_POSITIONAL_ARGUMENTS, &args[2])
        {
            builder.into_diagnostic(format_args!(
                "Too many positional arguments to function `{base_name}`: expected 2, got {}",
                args.len(),
                base_name = base_class.name(self.program_environment().python_version(db)),
            ));
        }

        if let Some(actual_name) = name
            && let Some(definition) = definition
            && let Some(assigned_name) = definition.name(db)
            && assigned_name.as_str() != actual_name
        {
            report_mismatched_type_name(
                &self.context,
                &MISMATCHED_ENUM_NAME,
                name_arg,
                base_class.name(env.python_version(db)),
                &assigned_name,
                Some(actual_name),
                name_type,
            );
        }

        let spec = self.infer_enum_spec(
            name,
            names_arg,
            start,
            base_class,
            mixin_type,
            has_too_many_positional || has_positional_keyword_conflict || !valid_mixin_type,
        );

        // Non-literal names use the ordinary `type[EnumSubclass]` overload result
        // instead of synthesizing a `DynamicEnumLiteral`.
        let Some(name) = name else {
            return SubclassOfType::try_from_type(db, env, base_class.to_class_literal(db, env));
        };

        let anchor = self.create_dynamic_enum_anchor(call_expr, definition, spec);
        let enum_lit = DynamicEnumLiteral::new(db, name, anchor, base_class, mixin_type);
        if let Err(error) = enum_lit.try_mro(db) {
            report_mro_error_kind(
                &self.context,
                error,
                enum_lit.name(db),
                call_expr,
                None,
                None,
            );
        }
        Some(Type::ClassLiteral(ClassLiteral::DynamicEnum(enum_lit)))
    }

    fn infer_enum_name_argument(
        &self,
        name_arg: &ast::Expr,
        name_type: Type<'db>,
        base_class: KnownClass,
    ) -> Option<&'db str> {
        let db = self.db();

        let Some(name_literal) = name_type.resolve_string_literal(db) else {
            let env = self.program_environment();
            if !name_type.is_assignable_to(db, env, KnownClass::Str.to_instance(db, env))
                && let Some(builder) = self.context.report_lint(&INVALID_ARGUMENT_TYPE, name_arg)
            {
                let mut diagnostic = builder.into_diagnostic(format_args!(
                    "Invalid argument to parameter `value` of `{base_name}()`",
                    base_name = base_class.name(env.python_version(db))
                ));
                diagnostic.set_primary_annotation_message(format_args!(
                    "Expected `str`, found `{}`",
                    name_type.display(db, env)
                ));
            }
            return None;
        };

        Some(name_literal.value(db))
    }

    fn infer_enum_start_argument(&mut self, value: &ast::Expr) -> Type<'db> {
        let db = self.db();
        let ty = self.expression_type(value);
        if let Some(literal) = ty.as_int_literal() {
            return Type::int_literal(literal);
        }

        let env = self.program_environment();
        let int = KnownClass::Int.to_instance(db, env);
        if ty.is_assignable_to(db, env, int) {
            return int;
        }

        if let Some(builder) = self.context.report_lint(&INVALID_ARGUMENT_TYPE, value) {
            builder.into_diagnostic(format_args!(
                "Expected `int` for `start` argument, got `{}`",
                ty.display(db, env),
            ));
        }

        Type::int_literal(1)
    }

    fn infer_enum_mixin_argument(
        &mut self,
        value: &ast::Expr,
        base_class: KnownClass,
    ) -> (Option<Type<'db>>, bool) {
        let db = self.db();
        let ty = self.expression_type(value);
        let env = self.program_environment();
        if let Some(class_lit) = ty.as_class_literal() {
            if class_lit.is_typed_dict(db)
                && let Some(builder) = self.context.report_lint(&INVALID_BASE, value)
            {
                builder.into_diagnostic(format_args!(
                    "TypedDict class `{}` cannot be used as an enum mixin",
                    ty.display(db, env),
                ));
                return (None, false);
            }

            let Some(mixin_class) = ty.to_class_type(db) else {
                return (Some(ty), true);
            };
            let Some(enum_base) = base_class.to_class_literal(db, env).to_class_type(db) else {
                return (Some(ty), true);
            };
            let constraints = ConstraintSetBuilder::new();
            if !mixin_class.could_coexist_in_mro_with(db, env, enum_base, &constraints)
                && let Some(builder) = self.context.report_lint(&INVALID_BASE, value)
            {
                builder.into_diagnostic(format_args!(
                    "Class `{}` cannot be used as an enum mixin with `{}`",
                    mixin_class.name(db),
                    base_class.name(self.program_environment().python_version(db)),
                ));
                return (None, false);
            }
            return (Some(ty), true);
        }

        if ty.is_dynamic() {
            return (Some(ty), true);
        }

        if let Some(builder) = self.context.report_lint(&INVALID_ARGUMENT_TYPE, value) {
            builder.into_diagnostic(format_args!(
                "Expected a class for `type` argument, got `{}`",
                ty.display(db, env),
            ));
        }

        (None, false)
    }

    fn infer_enum_spec(
        &mut self,
        class_name: Option<&str>,
        names_arg: &ast::Expr,
        start: Type<'db>,
        base_class: KnownClass,
        mixin_type: Option<Type<'db>>,
        has_invalid_arguments: bool,
    ) -> EnumSpec<'db> {
        let db = self.db();
        let env = self.program_environment();
        let unknown = || EnumSpec::new(db, Box::default(), Box::default(), false);
        if has_invalid_arguments {
            return unknown();
        }

        let (entries, value_form): (Vec<_>, _) = match self.parse_enum_members_arg(names_arg) {
            EnumMembersArgParseResult::Names(names) => (
                // The functional API generates values for *all* names before assigning
                // them to the namespace. A dunder still advances the next generated value.
                enum_members_from_names(&self.context, names, start, base_class)
                    .into_iter()
                    .map(|(name, value)| (name, value, None))
                    .collect(),
                EnumMemberValueForm::Generated,
            ),
            EnumMembersArgParseResult::Pairs(pairs) => (
                pairs
                    .into_iter()
                    .map(|(name, expr)| (name, self.expression_type(expr), Some(expr)))
                    .collect(),
                EnumMemberValueForm::Explicit,
            ),
            EnumMembersArgParseResult::Unknown => return unknown(),
            EnumMembersArgParseResult::Invalid => {
                self.report_invalid_enum_names_argument(names_arg, base_class);
                return unknown();
            }
        };

        let mut members = FxIndexMap::default();
        let mut nonmembers = FxIndexMap::default();
        let mut ignored = FxHashSet::default();
        let mut history = EnumAutoHistory::default();
        for (name, value, expr) in entries {
            if name == "_ignore_" {
                let Some(names) = self.enum_ignored_names_argument(value, expr) else {
                    return unknown();
                };
                if names.iter().any(|name| members.contains_key(name)) {
                    // An _ignore_ directive cannot retroactively remove an enum member.
                    return unknown();
                }
                ignored = names;
                continue;
            }
            if matches!(name.as_str(), "_order_" | "__order__") {
                continue;
            }
            if members.contains_key(&name) {
                // An existing member can never be reassigned, even to a nonmember.
                return unknown();
            }
            let (kind, value) = if ignored.contains(&name)
                || is_enum_attribute_name(&name, class_name, env.python_version(db))
            {
                (EnumEntryKind::Nonmember, value)
            } else if value_form == EnumMemberValueForm::Explicit {
                let next_value = || {
                    if nonmembers.contains_key("_generate_next_value_") {
                        Type::unknown()
                    } else {
                        history.next_value(db, env, base_class, &name)
                    }
                };
                let Some(entry) = classify_enum_value(db, env, value, next_value) else {
                    return unknown();
                };
                entry
            } else {
                (EnumEntryKind::Member, value)
            };
            match kind {
                EnumEntryKind::Member => {
                    if nonmembers.contains_key(&name) {
                        // A member cannot overwrite an existing class attribute either.
                        return unknown();
                    }
                    history = history.with_value(db, env, value);
                    members.insert(name, value);
                }
                EnumEntryKind::Nonmember => {
                    nonmembers.insert(name, value);
                }
            }
        }

        // Only the final _ignore_ list is removed when the namespace becomes a class.
        nonmembers.retain(|name, _| !ignored.contains(name));
        // EnumType saves the member constructor and restores Enum.__new__ for value lookups.
        let custom_new = nonmembers.swap_remove("__new__");
        if let Some(constructor) = custom_new {
            nonmembers.insert(Name::new("__new_member__"), constructor);
        }
        let members = members.into_iter().collect();
        let members = if custom_new.is_some() || nonmembers.contains_key("__init__") {
            // A custom constructor can change the values and aliases of every member.
            None
        } else if let Some(mixin) = mixin_type {
            match TypeMixinMemberBehavior::from_mixin(db, mixin, value_form) {
                TypeMixinMemberBehavior::ConvertedValues => {
                    apply_generated_type_mixin_member_values(&self.context, mixin, members)
                }
                TypeMixinMemberBehavior::UnknownMembers => None,
                TypeMixinMemberBehavior::Precise => Some(members),
            }
        } else {
            Some(members)
        };
        let has_known_members = members.is_some();
        EnumSpec::new(
            db,
            members.unwrap_or_default().into_boxed_slice(),
            nonmembers.into_iter().collect::<Box<[_]>>(),
            has_known_members,
        )
    }

    fn enum_ignored_names_argument(
        &mut self,
        ty: Type<'db>,
        expr: Option<&ast::Expr>,
    ) -> Option<FxHashSet<Name>> {
        let db = self.db();
        if let Some(ast::Expr::List(list)) = expr {
            return list
                .elts
                .iter()
                .map(|elt| {
                    Some(Name::new(
                        self.expression_type(elt).as_string_literal()?.value(db),
                    ))
                })
                .collect();
        }
        if let Some(literal) = ty.as_string_literal() {
            return Some(enum_names_from_string(literal.value(db)).collect());
        }
        ty.tuple_instance_spec(db, self.program_environment())?
            .as_fixed_length()?
            .iter_all_elements()
            .map(|ty| Some(Name::new(ty.as_string_literal()?.value(db))))
            .collect()
    }

    fn create_dynamic_enum_anchor(
        &mut self,
        call_expr: &ast::ExprCall,
        definition: Option<Definition<'db>>,
        spec: EnumSpec<'db>,
    ) -> DynamicEnumAnchor<'db> {
        match definition {
            Some(definition) => DynamicEnumAnchor::Definition { definition, spec },
            None => DynamicEnumAnchor::ScopeOffset {
                scope: self.scope(),
                offset: self.dynamic_class_scope_offset(call_expr),
                spec,
            },
        }
    }

    /// Parse the `names` argument of a functional enum call.
    ///
    /// Handles forms like:
    /// - `"RED GREEN BLUE"` (space/comma-separated string)
    /// - `["RED", "GREEN", "BLUE"]` (list of strings)
    /// - `[("RED", 1), ("GREEN", 2)]` (list of tuples)
    /// - `{"RED": 1, "GREEN": 2}` (dict mapping)
    fn parse_enum_members_arg<'ast>(
        &mut self,
        names_arg: &'ast ast::Expr,
    ) -> EnumMembersArgParseResult<'ast> {
        let db = self.db();
        let ty = self.expression_type(names_arg);
        if let Some(string_lit) = ty.as_string_literal() {
            return EnumMembersArgParseResult::Names(
                enum_names_from_string(string_lit.value(db)).collect(),
            );
        }

        let elts = match names_arg {
            ast::Expr::List(list) => Some(list.elts.as_slice()),
            ast::Expr::Tuple(tup) => Some(tup.elts.as_slice()),
            _ => None,
        };
        if let Some(elts) = elts {
            return self.parse_enum_members_from_sequence(elts);
        }

        if let ast::Expr::Dict(dict) = names_arg {
            return self.parse_enum_members_from_dict(dict);
        }

        let env = self.program_environment();
        if ty.is_dynamic() || ty.is_assignable_to(db, env, enum_names_type(db, env)) {
            EnumMembersArgParseResult::Unknown
        } else {
            EnumMembersArgParseResult::Invalid
        }
    }

    fn parse_enum_members_from_sequence<'ast>(
        &mut self,
        elts: &'ast [ast::Expr],
    ) -> EnumMembersArgParseResult<'ast> {
        let mut names = Vec::with_capacity(elts.len());
        let mut explicit_members = Vec::with_capacity(elts.len());
        let mut form = None;
        let mut has_opaque_members = false;

        for elt in elts {
            if matches!(elt, ast::Expr::Starred(_)) {
                return EnumMembersArgParseResult::Invalid;
            }
            match self.classify_sequence_enum_member(elt) {
                SequenceEnumMember::NameKnown(name) => {
                    if matches!(form, Some(SequenceEnumMemberForm::Pairs)) {
                        return EnumMembersArgParseResult::Invalid;
                    }
                    form = Some(SequenceEnumMemberForm::Names);
                    names.push(name);
                }
                SequenceEnumMember::NameOpaque => {
                    if matches!(form, Some(SequenceEnumMemberForm::Pairs)) {
                        return EnumMembersArgParseResult::Invalid;
                    }
                    form = Some(SequenceEnumMemberForm::Names);
                    has_opaque_members = true;
                }
                SequenceEnumMember::PairKnown(name, value) => {
                    if matches!(form, Some(SequenceEnumMemberForm::Names)) {
                        return EnumMembersArgParseResult::Invalid;
                    }
                    form = Some(SequenceEnumMemberForm::Pairs);
                    explicit_members.push((name, value));
                }
                SequenceEnumMember::PairOpaque => {
                    if matches!(form, Some(SequenceEnumMemberForm::Names)) {
                        return EnumMembersArgParseResult::Invalid;
                    }
                    form = Some(SequenceEnumMemberForm::Pairs);
                    has_opaque_members = true;
                }
                SequenceEnumMember::Invalid => return EnumMembersArgParseResult::Invalid,
            }
        }

        if has_opaque_members {
            return EnumMembersArgParseResult::Unknown;
        }

        if matches!(form, Some(SequenceEnumMemberForm::Pairs)) {
            EnumMembersArgParseResult::Pairs(explicit_members)
        } else {
            EnumMembersArgParseResult::Names(names)
        }
    }

    /// Parse enum members from a dict literal like `{"RED": 1, "GREEN": 2}`.
    fn parse_enum_members_from_dict<'ast>(
        &mut self,
        dict: &'ast ast::ExprDict,
    ) -> EnumMembersArgParseResult<'ast> {
        let db = self.db();
        let mut members = FxIndexMap::default();
        let mut has_opaque_keys = false;
        let env = self.program_environment();
        for item in &dict.items {
            let Some(key) = &item.key else {
                return EnumMembersArgParseResult::Invalid;
            };
            let key_ty = self.expression_type(key);
            let Some(string_lit) = key_ty.as_string_literal() else {
                if key_ty.is_dynamic()
                    || key_ty.is_assignable_to(db, env, KnownClass::Str.to_instance(db, env))
                {
                    has_opaque_keys = true;
                    continue;
                }
                return EnumMembersArgParseResult::Invalid;
            };
            let name = Name::new(string_lit.value(db));
            members.insert(name, &item.value);
        }
        if has_opaque_keys {
            EnumMembersArgParseResult::Unknown
        } else {
            EnumMembersArgParseResult::Pairs(members.into_iter().collect())
        }
    }

    /// Extract a `(name, value)` pair from a tuple element like `("RED", 1)`.
    fn parse_explicit_enum_member<'ast>(
        &mut self,
        elt: &'ast ast::Expr,
    ) -> Option<(Name, &'ast ast::Expr)> {
        let pair = match elt {
            ast::Expr::Tuple(tup) => &tup.elts,
            ast::Expr::List(list) => &list.elts,
            _ => return None,
        };
        let [name_expr, value_expr] = &**pair else {
            return None;
        };
        let db = self.db();
        let name_ty = self.expression_type(name_expr);
        let name = Name::new(name_ty.as_string_literal()?.value(db));
        Some((name, value_expr))
    }

    /// Returns `true` if `elt` could be an explicit `(name, value)` member pair.
    ///
    /// This is used when the name position is not a known string literal, but
    /// is still compatible with `str`.
    fn is_potential_explicit_enum_member(&mut self, elt: &ast::Expr) -> bool {
        let db = self.db();
        let pair = match elt {
            ast::Expr::Tuple(tup) => &tup.elts,
            ast::Expr::List(list) => &list.elts,
            _ => return false,
        };
        let [name_expr, _value_expr] = &**pair else {
            return false;
        };
        let name_ty = self.expression_type(name_expr);
        let env = self.program_environment();
        name_ty.is_dynamic()
            || name_ty.is_assignable_to(db, env, KnownClass::Str.to_instance(db, env))
    }

    /// Classifies one element from a sequence-form `names` argument.
    ///
    /// This distinguishes between known names, opaque names, known explicit
    /// pairs, opaque explicit pairs, and definitely invalid elements.
    fn classify_sequence_enum_member<'ast>(
        &mut self,
        elt: &'ast ast::Expr,
    ) -> SequenceEnumMember<'ast> {
        let db = self.db();
        let ty = self.expression_type(elt);
        if let Some(string_lit) = ty.as_string_literal() {
            return SequenceEnumMember::NameKnown(Name::new(string_lit.value(db)));
        }
        if let Some((name, value)) = self.parse_explicit_enum_member(elt) {
            return SequenceEnumMember::PairKnown(name, value);
        }
        let env = self.program_environment();
        if ty.is_dynamic() || ty.is_assignable_to(db, env, KnownClass::Str.to_instance(db, env)) {
            return SequenceEnumMember::NameOpaque;
        }
        if self.is_potential_explicit_enum_member(elt) {
            return SequenceEnumMember::PairOpaque;
        }
        SequenceEnumMember::Invalid
    }

    fn report_invalid_enum_names_argument(
        &mut self,
        names_arg: &ast::Expr,
        base_class: KnownClass,
    ) {
        let db = self.db();
        let base_name = base_class.name(self.program_environment().python_version(db));
        let names_ty = self.expression_type(names_arg);
        if let Some(builder) = self.context.report_lint(&INVALID_ARGUMENT_TYPE, names_arg) {
            let env = self.program_environment();
            let mut diagnostic = builder.into_diagnostic(format_args!(
                "Invalid argument to parameter `names` of `{base_name}()`"
            ));
            diagnostic.set_primary_annotation_message(format_args!(
                "Expected `{}`, found `{}`",
                enum_names_type(db, env).display(db, env),
                names_ty.display(db, env),
            ));
        }
    }
}
