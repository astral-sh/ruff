#![warn(
    clippy::disallowed_methods,
    reason = "Prefer System trait methods over std methods in ty crates"
)]
use ruff_db::vendored::{Compression, VendoredEntry, VendoredFileSystem};
use std::sync::LazyLock;

/// The source commit of the vendored typeshed.
pub const SOURCE_COMMIT: &str =
    include_str!("../vendor/typeshed/source_commit.txt").trim_ascii_end();

static_assertions::const_assert_eq!(SOURCE_COMMIT.len(), 40);

// The file paths here are hardcoded in this crate's `build.rs` script.
// Luckily this crate will fail to build if these files aren't available at build time.
#[expect(
    clippy::unreadable_literal,
    reason = "The index is generated by `build.rs`."
)]
static TYPESHED_INDEX: &[VendoredEntry] = include!(concat!(env!("OUT_DIR"), "/typeshed_index.rs"));
static TYPESHED_BYTES: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/typeshed.bin"));

#[cfg(feature = "zstd")]
const COMPRESSION: Compression = Compression::Zstd;
#[cfg(all(not(feature = "zstd"), feature = "deflate"))]
const COMPRESSION: Compression = Compression::Deflate;
#[cfg(not(any(feature = "zstd", feature = "deflate")))]
const COMPRESSION: Compression = Compression::Stored;

pub fn file_system() -> &'static VendoredFileSystem {
    static VENDORED_TYPESHED_STUBS: LazyLock<VendoredFileSystem> = LazyLock::new(|| {
        VendoredFileSystem::new_static(TYPESHED_INDEX, TYPESHED_BYTES, COMPRESSION).unwrap()
    });
    &VENDORED_TYPESHED_STUBS
}

#[cfg(test)]
mod tests {
    #![expect(
        clippy::disallowed_methods,
        reason = "These tests compare embedded contents with the source files on disk."
    )]

    use std::path::Path;

    use ruff_db::vendored::VendoredPath;

    use super::*;

    #[test]
    fn typeshed_created_at_build_time() {
        let functools = file_system()
            .read_to_string("stdlib/functools.pyi")
            .unwrap();
        assert!(functools.contains("def update_wrapper("));
    }

    #[test]
    fn typeshed_vfs_consistent_with_vendored_stubs() {
        let vendored_typeshed_dir = Path::new("vendor/typeshed").canonicalize().unwrap();
        let vendored_typeshed_stubs = file_system();

        let mut empty_iterator = true;
        for entry in walkdir::WalkDir::new(&vendored_typeshed_dir).min_depth(1) {
            empty_iterator = false;
            let entry = entry.unwrap();
            let absolute_path = entry.path();
            let file_type = entry.file_type();

            let relative_path = absolute_path
                .strip_prefix(&vendored_typeshed_dir)
                .unwrap_or_else(|_| {
                    panic!("Expected {absolute_path:?} to be a child of {vendored_typeshed_dir:?}")
                });

            let vendored_path = <&VendoredPath>::try_from(relative_path)
                .unwrap_or_else(|_| panic!("Expected {relative_path:?} to be valid UTF-8"));

            assert!(
                vendored_typeshed_stubs.exists(vendored_path),
                "Expected {vendored_path:?} to exist in the `VendoredFileSystem`!

                Vendored file system:

                {vendored_typeshed_stubs:#?}
                "
            );

            let vendored_path_kind = vendored_typeshed_stubs
                .metadata(vendored_path)
                .unwrap_or_else(|_| {
                    panic!(
                        "Expected metadata for {vendored_path:?} to be retrievable from the `VendoredFileSystem!

                        Vendored file system:

                        {vendored_typeshed_stubs:#?}
                        "
                    )
                })
                .kind();

            assert_eq!(
                vendored_path_kind.is_directory(),
                file_type.is_dir(),
                "{vendored_path:?} had type {vendored_path_kind:?}, inconsistent with fs path {relative_path:?}: {file_type:?}"
            );

            if file_type.is_file() {
                let mut expected = std::fs::read_to_string(absolute_path).unwrap();
                if relative_path == Path::new("stdlib/VERSIONS") {
                    expected.push_str("ty_extensions: 3.0-\n");
                }
                assert_eq!(
                    vendored_typeshed_stubs
                        .read_to_string(vendored_path)
                        .unwrap(),
                    expected,
                    "contents differ for {vendored_path:?}"
                );
            }
        }

        assert!(
            !empty_iterator,
            "Expected there to be at least one file or directory in the vendored typeshed stubs!"
        );
    }

    #[test]
    fn ty_extensions_are_included() {
        for path in ["__init__.pyi", "_internal.pyi", "pydantic.pyi"] {
            assert_eq!(
                file_system()
                    .read_to_string(format!("stdlib/ty_extensions/{path}"))
                    .unwrap(),
                std::fs::read_to_string(Path::new("ty_extensions").join(path)).unwrap(),
            );
        }
        assert!(file_system().is_directory("stdlib/ty_extensions"));
    }

    #[test]
    fn concurrent_reads() {
        std::thread::scope(|scope| {
            for path in [
                "stdlib/builtins.pyi",
                "stdlib/functools.pyi",
                "stdlib/asyncio/tasks.pyi",
                "stdlib/ty_extensions/__init__.pyi",
            ] {
                let expected = file_system().read_to_string(path).unwrap();
                let fs = file_system().clone();
                scope.spawn(move || {
                    for _ in 0..16 {
                        assert_eq!(fs.read_to_string(path).unwrap(), expected);
                    }
                });
            }
        });
    }
}
