    fn id(index: u32, generation: u32) -> Id {
        assert!(index < Id::MAX_U32);
        Id::from_bits((u64::from(generation) << 32) | (u64::from(index) + 1))
    }

    fn hash(value: &impl Hash) -> u64 {
        let mut hasher = DefaultHasher::new();
        value.hash(&mut hasher);
        hasher.finish()
    }

    #[test]
    fn empty() {
        let mut mutable = SalsaIdSet::<Id>::new();
        assert!(mutable.is_empty());
        assert_eq!(mutable.len(), 0);
        assert!(!mutable.contains(id(0, 0)));
        assert!(!mutable.remove(id(0, 0)));
        let set = mutable.freeze();
        assert_eq!(set, ImmutableSalsaIdSet::new());
        assert!(set.is_empty());
        assert_eq!(set.len(), 0);
        assert_eq!(set.ids().next(), None);
        assert_eq!(set.get_heap_size(), 0);
    }

    #[test]
    fn word_boundaries_and_generations() {
        let values = [
            id(0, 0),
            id(63, 0),
            id(64, 0),
            id(127, 0),
            id(128, 0),
            id(64, 1),
            id(0, 2),
            id(Id::MAX_U32 - 1, u32::MAX),
        ];
        let mut mutable = SalsaIdSet::new();
        for value in values.into_iter().rev() {
            assert!(mutable.insert(value));
            assert!(!mutable.insert(value));
        }
        assert_eq!(mutable.len(), values.len() as u64);
        assert_eq!(mutable.iter().collect::<Vec<_>>(), values);
        let frozen = mutable.freeze();
        assert_eq!(frozen.iter().collect::<Vec<_>>(), values);
        assert_eq!(frozen.to_mutable().freeze(), frozen);
        assert_eq!(frozen.len(), values.len() as u64);
        for value in values {
            assert!(frozen.contains(value));
        }
        for absent in [id(62, 0), id(65, 1), id(64, 2), id(0, u32::MAX)] {
            assert!(!frozen.contains(absent));
        }
    }

    #[test]
    fn canonical_after_removal() {
        let values = [id(0, 0), id(64, 0), id(128, 0)];
        let mut mutable = SalsaIdSet::from_iter(values);
        assert!(!mutable.remove(id(65, 0)));
        assert!(mutable.remove(values[1]));
        assert!(!mutable.remove(values[1]));
        let with_gap = ImmutableSalsaIdSet::from_iter([values[2], values[0]]);
        assert_eq!(hash(&mutable), hash(&with_gap));
        assert_eq!(mutable.clone().freeze(), with_gap);
        assert!(mutable.insert(values[1]));
        assert_eq!(
            mutable.clone().freeze(),
            ImmutableSalsaIdSet::from_iter(values)
        );
        for value in values {
            assert!(mutable.remove(value));
        }
        assert_eq!(mutable.freeze(), ImmutableSalsaIdSet::default());
    }

    #[test]
    fn packed_runs() {
        let page = SalsaIdSet::from_iter((0..128).map(|index| id(index, 0)));
        assert!(!page.chunks.spilled());
        let page = page.freeze();
        assert_eq!(page.len(), 128);
        // One header and two bitmap words, with no per-run allocation or capacity.
        assert_eq!(page.get_heap_size(), 3 * size_of::<u64>());
        assert_eq!(size_of_val(&page), size_of::<Box<[u64]>>());

        let mutable = SalsaIdSet::from_iter((0..130).map(|word| id(word * 64, 0)));
        let set = mutable.clone().freeze();
        assert_eq!(set.get_heap_size(), (130 + 3) * size_of::<u64>());
        assert_eq!(
            set.ids().collect::<Vec<_>>(),
            mutable.ids().collect::<Vec<_>>()
        );
        assert_eq!(hash(&set), hash(&mutable));

        let removed = ImmutableSalsaIdSet::from_iter([id(63 * 64, 0), id(64 * 64, 0)]);
        let remaining = set.difference(&removed);
        let expected = ImmutableSalsaIdSet::from_iter(
            (0..130)
                .filter(|word| ![63, 64].contains(word))
                .map(|word| id(word * 64, 0)),
        );
        assert_eq!(remaining, expected);
        assert_eq!(remaining.union(&removed), set);
    }

    #[test]
    fn algebra_with_overlapping_words() {
        let left = ImmutableSalsaIdSet::from_iter([
            id(0, 0),
            id(1, 0),
            id(63, 0),
            id(64, 0),
            id(128, 0),
            id(64, 1),
        ]);
        let right = ImmutableSalsaIdSet::from_iter([
            id(1, 0),
            id(62, 0),
            id(63, 0),
            id(127, 0),
            id(256, 0),
            id(64, 2),
        ]);
        assert_eq!(
            left.intersection(&right),
            ImmutableSalsaIdSet::from_iter([id(1, 0), id(63, 0)])
        );
        assert_eq!(
            left.difference(&right),
            ImmutableSalsaIdSet::from_iter([id(0, 0), id(64, 0), id(128, 0), id(64, 1)])
        );
        assert_eq!(
            left.union(&right),
            ImmutableSalsaIdSet::from_iter(left.iter().chain(right.iter()))
        );
        let empty = ImmutableSalsaIdSet::new();
        assert_eq!(left.union(&empty), left);
        assert_eq!(empty.union(&left), left);
        assert_eq!(left.difference(&empty), left);
        assert!(empty.difference(&left).is_empty());
        assert!(left.intersection(&empty).is_empty());
        assert!(empty.intersection(&left).is_empty());
    }

    // The collection only needs AsId and Copy; hashing and equality must not add
    // corresponding bounds on the type of its members.
    #[derive(Clone, Copy)]
    struct MinimalId(Id);

    impl AsId for MinimalId {
        fn as_id(&self) -> Id {
            self.0
        }
    }

    #[test]
    fn minimal_bounds() {
        let mut mutable = SalsaIdSet::new();
        let value = MinimalId(id(65, 42));
        mutable.insert(value);
        assert!(mutable.contains(value));
        let set = mutable.clone().freeze();
        assert_eq!(set, set.clone());
        assert_eq!(hash(&mutable), hash(&set));
        assert!(set.contains(value));
        assert_eq!(set.ids().collect::<Vec<_>>(), [id(65, 42)]);
        assert_eq!(set.get_heap_size(), 2 * size_of::<u64>());
        assert!(mutable.remove(value));
        assert!(!mutable.contains(value));
    }

    fn arbitrary_id((index, generation): (u32, u32)) -> Id {
        id(index % Id::MAX_U32, generation)
    }

    #[quickcheck]
    fn mutation_matches_btree(operations: Vec<(u16, u8, bool)>) -> bool {
        let mut expected = BTreeSet::new();
        let mut mutable = SalsaIdSet::new();
        for (index, generation, insert) in operations {
            let value = id(u32::from(index % 512), u32::from(generation % 4));
            let (actual_changed, expected_changed) = if insert {
                (mutable.insert(value), expected.insert(value.as_bits()))
            } else {
                (mutable.remove(value), expected.remove(&value.as_bits()))
            };
            if actual_changed != expected_changed
                || mutable.contains(value) != expected.contains(&value.as_bits())
                || mutable.len() != expected.len() as u64
                || !mutable.ids().map(Id::as_bits).eq(expected.iter().copied())
            {
                return false;
            }
        }
        let frozen = mutable.clone().freeze();
        let mut reversed = frozen.iter().collect::<Vec<_>>();
        reversed.reverse();
        frozen.ids().map(Id::as_bits).eq(expected.iter().copied())
            && hash(&mutable) == hash(&frozen)
            && frozen == ImmutableSalsaIdSet::from_iter(reversed)
    }

    #[quickcheck]
    fn algebra_matches_btree(left: Vec<(u32, u32)>, right: Vec<(u32, u32)>) -> bool {
        let left: BTreeSet<_> = left
            .into_iter()
            .map(arbitrary_id)
            .map(Id::as_bits)
            .collect();
        let right: BTreeSet<_> = right
            .into_iter()
            .map(arbitrary_id)
            .map(Id::as_bits)
            .collect();
        let a = ImmutableSalsaIdSet::from_iter(left.iter().copied().map(Id::from_bits));
        let b = ImmutableSalsaIdSet::from_iter(right.iter().copied().map(Id::from_bits));
        let union = a.union(&b);
        let intersection = a.intersection(&b);
        let difference = a.difference(&b);
        union.ids().map(Id::as_bits).eq(left.union(&right).copied())
            && intersection
                .ids()
                .map(Id::as_bits)
                .eq(left.intersection(&right).copied())
            && difference
                .ids()
                .map(Id::as_bits)
                .eq(left.difference(&right).copied())
            && union == b.union(&a)
            && intersection == b.intersection(&a)
            && a.difference(&a).is_empty()
    }

    // Keep values in one interner shard so the revision test reliably reuses slots.
    #[derive(Clone, Copy, Debug, Eq, PartialEq, salsa::SalsaValue)]
    struct SameHash(u32);

    impl Hash for SameHash {
        fn hash<H: Hasher>(&self, state: &mut H) {
            0_u8.hash(state);
        }
    }

    #[salsa::interned(debug, revisions = 1)]
    struct Value<'db> {
        #[returns(copy)]
        value: SameHash,
    }

    #[salsa::interned(debug)]
    struct InternedSet<'db> {
        #[returns(ref)]
        values: ImmutableSalsaIdSet<Value<'db>>,
    }

    #[test]
    fn borrowed_interning() {
        let db = salsa::DatabaseImpl::new();
        let a = Value::new(&db, SameHash(10));
        let b = Value::new(&db, SameHash(20));
        let c = Value::new(&db, SameHash(30));
        let mutable = SalsaIdSet::from_iter([b, a, a]);
        let first = InternedSet::new(&db, &mutable);
        assert_eq!(first.values(&db).iter().collect::<Vec<_>>(), [a, b]);
        assert!(first.values(&db).contains(a));
        assert!(!first.values(&db).contains(c));
        assert_eq!(
            first,
            InternedSet::new(&db, ImmutableSalsaIdSet::from_iter([a, b]))
        );
        assert_eq!(first, InternedSet::new(&db, &SalsaIdSet::from_iter([a, b])));
        assert_ne!(first, InternedSet::new(&db, &SalsaIdSet::from_iter([a, c])));
    }

